#!/usr/bin/env python3
"""Export TEN VAD ONNX initializers to a C header for the firmware port."""

from pathlib import Path

import numpy as np
import onnx
from onnx import numpy_helper

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "tools" / "ten-vad.onnx"
OUT = ROOT / "src" / "ten_vad" / "weights.h"

# name -> C identifier
NAMES = {
    "const_fold_opt__178": "W_CONV0",
    "StatefulPartitionedCall/vad_model/separable_conv2d/separable_conv2d/ReadVariableOp_1:0": "W_CONV1",
    "StatefulPartitionedCall/vad_model/separable_conv2d/BiasAdd/ReadVariableOp:0": "B_CONV1",
    "const_fold_opt__179": "W_DW2",
    "StatefulPartitionedCall/vad_model/separable_conv1d/ExpandDims_2:0": "W_PW2",
    "StatefulPartitionedCall/vad_model/separable_conv1d/BiasAdd/ReadVariableOp:0": "B_PW2",
    "const_fold_opt__180": "W_DW3",
    "StatefulPartitionedCall/vad_model/separable_conv1d_1/ExpandDims_2:0": "W_PW3",
    "StatefulPartitionedCall/vad_model/separable_conv1d_1/BiasAdd/ReadVariableOp:0": "B_PW3",
    "W0__70": "W_LSTM1",
    "R0__71": "R_LSTM1",
    "B0__72": "B_LSTM1",
    "W0__99": "W_LSTM2",
    "R0__100": "R_LSTM2",
    "B0__101": "B_LSTM2",
    "StatefulPartitionedCall/vad_model/dense_3/Tensordot/ReadVariableOp:0": "W_DENSE3",
    "StatefulPartitionedCall/vad_model/dense_3/BiasAdd/ReadVariableOp:0": "B_DENSE3",
    "StatefulPartitionedCall/vad_model/dense_5/Tensordot/ReadVariableOp:0": "W_DENSE5",
    "StatefulPartitionedCall/vad_model/dense_5/BiasAdd/ReadVariableOp:0": "B_DENSE5",
}


def emit_array(name: str, arr: np.ndarray) -> str:
    flat = arr.astype(np.float32).ravel()
    lines = [f"static const float {name}[{flat.size}] = {{"]
    for i in range(0, flat.size, 8):
        chunk = ", ".join(f"{float(v):.9e}f" for v in flat[i : i + 8])
        lines.append("  " + chunk + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    model = onnx.load(str(MODEL))
    init = {i.name: numpy_helper.to_array(i) for i in model.graph.initializer}
    missing = [k for k in NAMES if k not in init]
    if missing:
        raise SystemExit(f"missing initializers: {missing}")

    parts = [
        "// Generated by tools/export_ten_vad_weights.py from ten-vad.onnx.",
        "// TEN VAD is Copyright (c) 2025 Agora and licensed under the",
        "// Apache License 2.0 with additional conditions; see LICENSE.",
        "#pragma once",
        "",
    ]
    for src, cname in NAMES.items():
        arr = init[src]
        parts.append(f"// {src} shape={list(arr.shape)}")
        parts.append(emit_array(cname, arr))
        parts.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts))
    total = sum(init[k].size for k in NAMES)
    print(f"wrote {OUT} ({total} floats)")


if __name__ == "__main__":
    main()
